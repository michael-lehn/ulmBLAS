#! /bin/sh
#
#  gen.sh EXPORTS OUTDIR: from the list of exported names of a backend
#  (EXPORTS, one name per line as nm prints them on macOS, with the leading
#  underscore) generate OUTDIR/names.h (the names for dlsym, their number)
#  and OUTDIR/trampolines.S (one trampoline per name: load the address
#  from ulmblas_dispatch_table, branch to it; x16 is the intra-procedure
#  call register, free at a call).  Only functions are listed in EXPORTS.
#
set -e
exports=$1
out=$2
count=`wc -l < "$exports" | tr -d ' '`

{
	echo "/*  generated by gen.sh, do not edit */"
	echo "#define ULMBLAS_DISPATCH_COUNT $count"
	echo "static const char *const ulmblas_dispatch_names[] = {"
	sed 's/^_//; s/.*/    "&",/' "$exports"
	echo "};"
} > "$out/names.h"

{
	echo "//  generated by gen.sh, do not edit"
	echo "	.section __TEXT,__text,regular,pure_instructions"
	awk '{
		printf "\n\t.globl %s\n\t.p2align 2\n%s:\n", $1, $1
		printf "\tadrp x16, _ulmblas_dispatch_table@PAGE\n"
		printf "\tadd x16, x16, _ulmblas_dispatch_table@PAGEOFF\n"
		printf "\tldr x16, [x16, #%d]\n", 8 * (NR - 1)
		printf "\tbr x16\n"
	}' "$exports"
	echo
	echo "	.subsections_via_symbols"
} > "$out/trampolines.S"
