#! /bin/sh
#
#  gen.sh FORMAT FUNCTIONS OUTDIR: from the list of the functions of a
#  backend (FUNCTIONS, one name per line, without the underscore that
#  Mach-O puts in front of C names) generate
#
#      OUTDIR/names.h        the names for dlsym/GetProcAddress, their number
#      OUTDIR/trampolines.S  one trampoline per name: load the address from
#                            ulmblas_dispatch_table[i], branch to it
#
#  FORMAT is the object format and architecture of the library:
#
#      macho-arm64   x16, the intra-procedure call register, is free at a
#                    call
#      elf-x86_64    an indirect jump through the table
#      coff-x86_64   Windows: if the entry is still empty, branch to a common
#                    slow path that saves the argument registers (rcx, rdx,
#                    r8, r9, xmm0-xmm3; rax and r10, r11 are free at a call),
#                    calls ulmblas_dispatch_resolve and jumps through the
#                    filled entry; the names are exported with -export
#                    directives (.drectve)
#
set -e
format=$1
functions=$2
out=$3
count=`wc -l < "$functions" | tr -d ' '`

{
	echo "/*  generated by gen.sh, do not edit */"
	echo "#define ULMBLAS_DISPATCH_COUNT $count"
	echo "static const char *const ulmblas_dispatch_names[] = {"
	sed 's/.*/    "&",/' "$functions"
	echo "};"
} > "$out/names.h"

case $format in
macho-arm64)
	{
		echo "//  generated by gen.sh, do not edit"
		echo "	.section __TEXT,__text,regular,pure_instructions"
		awk '{
			printf "\n\t.globl _%s\n\t.p2align 2\n_%s:\n", $1, $1
			printf "\tadrp x16, _ulmblas_dispatch_table@PAGE\n"
			printf "\tadd x16, x16, _ulmblas_dispatch_table@PAGEOFF\n"
			printf "\tldr x16, [x16, #%d]\n", 8 * (NR - 1)
			printf "\tbr x16\n"
		}' "$functions"
		echo
		echo "	.subsections_via_symbols"
	} > "$out/trampolines.S"
	;;
elf-x86_64)
	{
		echo "#  generated by gen.sh, do not edit"
		echo "	.text"
		awk '{
			printf "\n\t.globl %s\n\t.type %s, @function\n", $1, $1
			printf "\t.p2align 4\n%s:\n", $1
			printf "\tjmp *ulmblas_dispatch_table+%d(%%rip)\n", 8 * (NR - 1)
			printf "\t.size %s, .-%s\n", $1, $1
		}' "$functions"
		echo
		echo "	.section .note.GNU-stack,\"\",@progbits"
	} > "$out/trampolines.S"
	;;
coff-x86_64)
	{
		echo "#  generated by gen.sh, do not edit"
		echo "	.text"
		awk '{
			printf "\n\t.globl %s\n\t.def %s; .scl 2; .type 32; .endef\n", $1, $1
			printf "\t.p2align 4\n%s:\n", $1
			printf "\tmovq ulmblas_dispatch_table+%d(%%rip), %%rax\n", 8 * (NR - 1)
			printf "\ttestq %%rax, %%rax\n\tjz 1f\n\tjmpq *%%rax\n"
			printf "1:\tmovl $%d, %%eax\n\tjmp ulmblas_dispatch_slow\n", NR - 1
		}' "$functions"
		cat << 'EOF'

#  the slow path (first calls): at entry rsp = 8 (mod 16); 152 bytes:
#  32 of shadow space for the call, the four integer and the four vector
#  argument registers, the index
	.def ulmblas_dispatch_slow; .scl 3; .type 32; .endef
	.p2align 4
ulmblas_dispatch_slow:
	subq $152, %rsp
	movq %rcx, 32(%rsp)
	movq %rdx, 40(%rsp)
	movq %r8, 48(%rsp)
	movq %r9, 56(%rsp)
	movdqu %xmm0, 64(%rsp)
	movdqu %xmm1, 80(%rsp)
	movdqu %xmm2, 96(%rsp)
	movdqu %xmm3, 112(%rsp)
	movq %rax, 128(%rsp)
	call ulmblas_dispatch_resolve
	movq 32(%rsp), %rcx
	movq 40(%rsp), %rdx
	movq 48(%rsp), %r8
	movq 56(%rsp), %r9
	movdqu 64(%rsp), %xmm0
	movdqu 80(%rsp), %xmm1
	movdqu 96(%rsp), %xmm2
	movdqu 112(%rsp), %xmm3
	movq 128(%rsp), %rax
	addq $152, %rsp
	leaq ulmblas_dispatch_table(%rip), %r10
	jmpq *(%r10,%rax,8)

	.section .drectve
EOF
		awk '{ printf "\t.ascii \" -export:%s\"\n", $1 }' "$functions"
	} > "$out/trampolines.S"
	;;
*)
	echo "gen.sh: unknown format $format" >&2
	exit 2
	;;
esac
