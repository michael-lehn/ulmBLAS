"""Code generation of the GEMM tuning (make tune, see tune/README.md).

    gentable.py candidates OUT
        candidates.h for tune/gemm/measure.cc: the candidates of all sets
        of tune/gemm/candidates.py, each set under its build condition.

    gentable.py index SET
        the index of the candidate set SET in candidates.h (make tune
        TUNESET=SET: -DULMBLAS_TUNE_SET_INDEX=index)

    gentable.py table SET PLATFORM DATA TABLEDIR REPORT
        the selection table of the candidate set SET (e.g. double-sme) for
        PLATFORM (e.g. apple-m5) from the measurement DATA (output of
        measure run): TABLEDIR/PLATFORM-TYPE.h, the index TABLEDIR/tables.h
        of all tables in TABLEDIR, and a report (Markdown) REPORT.

The table: selection rules with a fixed structure (as in ATLAS), whose
thresholds and global choices are fitted to the measurements (fit_rules,
see tune/gemm/candidates.py).  Every point of the measurement grid
(m, n, k) stands for a cell of problems, bounded by the geometric means of
neighbouring grid values (the first cell starts at 0, the last one has no
upper bound); the thresholds are lower bounds of cells.

For comparison the report also shows the boxes of merged cells (below), the
best candidate per cell and a single candidate for all problems.

The default, the last entry of the table (for all problems), is the
candidate that is within NOISE of the best in the most cells.  A cell gets
another candidate than the default only if it is clearly better: its median
is at least GAIN above the one of the default, it is better than the
default in every pass (the medians of the passes), and it does not run the
same code as the default (same variant, problem within the blocks of
both).  Otherwise differences are taken as noise.  Of the candidates that
are clearly better and within NOISE of the best, the one that is so in the
most cells is taken (fewer, larger boxes).  The cells with other
candidates are merged into boxes (ranges of m, n and k), each an entry; a
box may also cover cells in which its candidate is within NOISE of the
best.  An entry for the default comes first for the problems smaller than
all boxes (m, n, k <= X): small problems need not scan the table.
"""
import collections, datetime, math, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import candidates as cand

NOISE = 0.02
GAIN = 0.03


def set_key(name):
    t, k = name.split("-", 1)
    return (t, k)


def cpp_name(s):
    return re.sub(r"[^A-Za-z0-9]", "_", s)


def write_candidates(out):
    lines = ["//", "//  Generated by tune/gemm/gentable.py from "
             "tune/gemm/candidates.py: do not edit.", "//", ""]
    first = True
    for index, ((t, k), s) in enumerate(cand.SETS.items()):
        #  ULMBLAS_TUNE_SET_INDEX (make tune TUNESET=...) picks one of the
        #  sets whose conditions hold
        lines.append("#%s (%s) && (!defined(ULMBLAS_TUNE_SET_INDEX) || "
                     "ULMBLAS_TUNE_SET_INDEX == %d)"
                     % ("if" if first else "elif", s["condition"], index))
        first = False
        for inc in s["includes"]:
            lines.append("#include <%s>" % inc)
        lines += [
            '#define ULMBLAS_TUNE_SET "%s-%s"' % (t, k),
            "typedef %s TuneT;" % s["type"],
            "struct TuneCandidate",
            "{",
            "    const char *name;",
            "    void (*run)(std::ptrdiff_t, std::ptrdiff_t, std::ptrdiff_t,",
            "                const TuneT &, bool, const TuneT *, std::ptrdiff_t,",
            "                std::ptrdiff_t, bool, const TuneT *, std::ptrdiff_t,",
            "                std::ptrdiff_t, const TuneT &, TuneT *, std::ptrdiff_t,",
            "                std::ptrdiff_t);",
            "};",
            "namespace tune {",
            "using namespace ulmBLAS;",
            "typedef %s B;" % s["backend"],
        ]
        measured = [c for c in s["candidates"] if not c.get("alias")]
        for i, c in enumerate(measured):
            lines.append("typedef %s Candidate%d;" % (c["frame"], i))
        lines += ["}", "static const TuneCandidate candidates[] = {"]
        for i, c in enumerate(measured):
            lines.append('    {"%s", &tune::Candidate%d::template run<'
                         'std::ptrdiff_t, TuneT, TuneT, TuneT, TuneT, TuneT>},'
                         % (c["name"], i))
        lines.append("};")
    lines.append("#endif")
    open(out, "w").write("\n".join(lines) + "\n")


def load(data):
    """per shape and candidate: the median over the passes, the medians of
    the passes, the smallest and largest sample.  The lines of a shape and
    candidate in DATA are the passes, in order."""
    passes = collections.defaultdict(lambda: collections.defaultdict(list))
    spread = collections.defaultdict(dict)
    for line in open(data):
        x = line.split()
        if len(x) < 7:
            continue
        p = (int(x[0]), int(x[1]), int(x[2]))
        passes[p][x[3]].append(float(x[4]))
        lo, hi = spread[p].get(x[3], (float(x[5]), float(x[6])))
        spread[p][x[3]] = (min(lo, float(x[5])), max(hi, float(x[6])))
    med = collections.defaultdict(dict)
    for p, r in passes.items():
        for c, v in r.items():
            v = sorted(v)
            med[p][c] = v[len(v) // 2]
    return med, passes, spread


def bounds(values):
    """cell bounds [lo, hi] for each grid value (hi = None: no limit)"""
    b = []
    for i, v in enumerate(values):
        lo = 0 if i == 0 else int(math.ceil(math.sqrt(values[i - 1] * v)))
        hi = None if i == len(values) - 1 else \
            int(math.ceil(math.sqrt(v * values[i + 1]))) - 1
        b.append((lo, hi))
    return b


def same_code(p, a, b):
    """candidates a and b run the same code for the shape p = (m, n, k):
    the same variant and p within the block sizes of both (one block in
    every dimension; the maximum block sizes do not matter then)"""
    m, n, k = p
    if a["blocks"] is None or b["blocks"] is None:
        return a is b
    return (a["variant"] == b["variant"] and
            all(m <= c["blocks"][0] and k <= c["blocks"][1] and
                n <= c["blocks"][2] for c in (a, b)))


def winners(med, passes, names, info):
    """the default and the candidate per cell"""
    count = collections.Counter()
    for p, r in med.items():
        top = max(r.values())
        for c in names:
            if r.get(c, 0) >= (1 - NOISE) * top:
                count[c] += 1
    default = max(names, key=lambda c: (count[c], -names.index(c)))
    def clear(p, c):
        r = med[p]
        return (r[c] >= (1 + GAIN) * r[default] and
                all(a > b for a, b in zip(passes[p][c], passes[p][default])) and
                not same_code(p, info[c], info[default]))

    #  acceptable per cell: within NOISE of the best and clearly better than
    #  the default; of these the one acceptable in the most cells (fewer,
    #  larger boxes)
    acceptable = {}
    for p, r in med.items():
        top = max(r.values())
        acceptable[p] = [c for c in names
                         if r.get(c, 0) >= (1 - NOISE) * top and clear(p, c)]
    often = collections.Counter(c for a in acceptable.values() for c in a)
    win = {}
    for p in med:
        a = acceptable[p]
        win[p] = max(a, key=lambda c: (often[c], med[p][c])) if a else default
    return default, win


def boxes(win, ok, default, ms, ns, ks):
    """greedy merging, starting at the cells with other candidates than the
    default: a box of candidate w grows over cells in which w is within
    NOISE of the best (ok), also cells of the default"""
    done = set()
    out = []
    for i, m in enumerate(ms):
        for j, n in enumerate(ns):
            for l, k in enumerate(ks):
                w = win.get((m, n, k))
                if w is None or w == default or (i, j, l) in done:
                    continue

                def fits(ii, jj, ll):
                    return all((ms[a], ns[b], ks[c]) in ok and
                               w in ok[(ms[a], ns[b], ks[c])] and
                               (a, b, c) not in done
                               for a in ii for b in jj for c in ll)
                i1 = i
                while i1 + 1 < len(ms) and fits([i1 + 1], [j], [l]):
                    i1 += 1
                j1 = j
                while j1 + 1 < len(ns) and fits(range(i, i1 + 1), [j1 + 1],
                                                [l]):
                    j1 += 1
                l1 = l
                while l1 + 1 < len(ks) and fits(range(i, i1 + 1),
                                                range(j, j1 + 1), [l1 + 1]):
                    l1 += 1
                for a in range(i, i1 + 1):
                    for b in range(j, j1 + 1):
                        for c in range(l, l1 + 1):
                            done.add((a, b, c))
                            win[(ms[a], ns[b], ks[c])] = w
                out.append((w, (i, i1), (j, j1), (l, l1)))
    return out


def fit_rules(med, s, ms, ns, ks, bm, bn, bk):
    """thresholds and global features of the selection rules of the set s
    (see tune/gemm/candidates.py) that maximize the geometric mean of the
    performance relative to the best candidate per cell.  Thresholds are
    lower bounds of cells (None: the rule never applies); of equal choices
    the one found first, i.e. with fewer rules, is kept."""
    rules = s["rules"]
    box, size, glob = rules.get("box"), rules.get("size"), rules.get("global", [])
    small = rules.get("small")
    byfeat = {}
    for c in s["candidates"]:
        byfeat[tuple(sorted(c["features"].items()))] = c["name"]

    def name(features):
        return byfeat[tuple(sorted(features.items()))]

    cells = sorted(med)
    logr = {p: {c: math.log(v / max(med[p].values())) for c, v in med[p].items()}
            for p in cells}
    #  Mmin, MNmin: None (the rule does not apply) or a lower bound; Nmin,
    #  Kmin: 0 (no condition) or a lower bound
    mopts = [None] + [b[0] for b in bm if b[0] > 0]
    nopts = [0] + [b[0] for b in bn if b[0] > 0]
    kopts = [0] + [b[0] for b in bk if b[0] > 0]
    mnopts = [None] + sorted({a[0] * b[0] for a in bm for b in bn
                              if a[0] * b[0] > 0})
    #  MNbig: None or a bound above MNmin (for m n >= MNbig the size feature
    #  regardless of k)
    def mbopts(MN):
        return [None] + [x for x in mnopts[1:] if MN is not None and x > MN]

    if box is None:
        mopts, nopts = [None], [0]
    if size is None:
        mnopts, kopts = [None], [0]

    best = None
    for g in range(1 << len(glob)):
        gf = {f: bool(g >> i & 1) for i, f in enumerate(glob)}
        if small:
            gf[small] = False
        for M in mopts:
            for N in (nopts if M is not None else [0]):
                large = [M is not None and p[0] >= M and p[1] >= N
                         for p in cells]
                for MN in mnopts:
                    for K in (kopts if MN is not None else [0]):
                        for MB in (mbopts(MN) if K > 0 else [None]):
                            total = 0.0
                            for i, p in enumerate(cells):
                                f = dict(gf)
                                if box:
                                    f[box] = large[i]
                                if size:
                                    mn = p[0] * p[1]
                                    f[size] = (MN is not None and mn >= MN and
                                               (p[2] >= K or
                                                (MB is not None and mn >= MB)))
                                total += logr[p][name(f)]
                            score = total / len(cells)
                            if best is None or score > best[0] + 1e-4:
                                best = (score, gf, M, N, MN, K, MB)
    score, gf, M, N, MN, K, MB = best

    #  the entries: (mlo, mhi, nlo, nhi, klo, khi, minMN, candidate)
    rows = []

    def cand(b, z):
        f = dict(gf)
        if box:
            f[box] = b
        if size:
            f[size] = z
        return name(f)
    if M is not None and MN is not None:
        rows.append((M, None, N, None, K, None, MN, cand(True, True)))
        if MB is not None:
            rows.append((M, None, N, None, 0, None, MB, cand(True, True)))
    if M is not None:
        rows.append((M, None, N, None, 0, None, 0, cand(True, False)))
    if MN is not None:
        rows.append((0, None, 0, None, K, None, MN, cand(False, True)))
        if MB is not None:
            rows.append((0, None, 0, None, 0, None, MB, cand(False, True)))
    rows.append((0, None, 0, None, 0, None, 0, cand(False, False)))

    def applies(r, p):
        inf = float("inf")
        return (r[0] <= p[0] <= (inf if r[1] is None else r[1]) and
                r[2] <= p[1] <= (inf if r[3] is None else r[3]) and
                r[4] <= p[2] <= (inf if r[5] is None else r[5]) and
                p[0] * p[1] >= r[6] and
                (len(r) < 9 or r[8] is None or p[0] * p[2] <= r[8]))

    def select(p):
        for r in rows:
            if applies(r, p):
                return r[7]
    thresholds = {"Mmin": M, "Nmin": N, "MNmin": MN, "Kmin": K, "MNbig": MB}
    thresholds.update(gf)

    #  the kernel for small matrices: for m k <= MK1, or m <= M2 and m k <=
    #  MK2 (grid points as upper bounds), before the other rules; fitted
    #  after them, against what they select
    if small:
        fs = dict(gf)
        fs[small] = True
        for f in (box, size):
            if f:
                fs[f] = False
        sname = name(fs)
        rest = {p: logr[p][select(p)] for p in cells}
        gain = {p: logr[p][sname] - rest[p] for p in cells}
        #  upper bounds: the grid points themselves, not the upper bounds of
        #  their cells (beyond a measured point the kernel may collapse,
        #  e.g. when A no longer fits in the cache; the grid does not show
        #  where between two points)
        mkopts = [None] + sorted({m * k for m in ms for k in ks})
        m2opts = [None] + list(ms)
        sbest = (0.0, None, None, None)
        for MK1 in mkopts:
            for M2 in m2opts:
                for MK2 in (mkopts[1:] if M2 is not None else [None]):
                    if MK1 is not None and MK2 is not None and MK2 <= MK1:
                        continue
                    total = 0.0
                    for p in cells:
                        mk = p[0] * p[2]
                        if ((MK1 is not None and mk <= MK1) or
                                (M2 is not None and p[0] <= M2 and
                                 mk <= MK2)):
                            total += gain[p]
                    if total / len(cells) > sbest[0] + 1e-4:
                        sbest = (total / len(cells), MK1, M2, MK2)
        _, MK1, M2, MK2 = sbest
        srows = []
        if MK1 is not None:
            srows.append((0, None, 0, None, 0, None, 0, sname, MK1))
        if M2 is not None:
            srows.append((0, M2, 0, None, 0, None, 0, sname, MK2))
        rows[:0] = srows
        thresholds.update({"small MKmax": MK1, "small Mmax": M2,
                           "small MKmax (m <= Mmax)": MK2})
    return rows, select, thresholds


def box_rows(bx, default, bm, bn, bk):
    """the entries of the boxes (bounds of their cells), the default last;
    an entry for the default first for problems below all boxes"""
    rows = []
    for w, (i0, i1), (j0, j1), (l0, l1) in bx:
        rows.append((bm[i0][0], bm[i1][1], bn[j0][0], bn[j1][1], bk[l0][0],
                     bk[l1][1], 0, w))
    if rows:
        mlo = min(r[0] for r in rows)
        nlo = min(r[2] for r in rows)
        klo = min(r[4] for r in rows)
        first = [(0, mlo - 1, 0, None, 0, None, 0, default)] if mlo > 0 else []
        if not first and nlo > 0:
            first = [(0, None, 0, nlo - 1, 0, None, 0, default)]
        if not first and klo > 0:
            first = [(0, None, 0, None, 0, klo - 1, 0, default)]
        rows = first + rows
    rows.append((0, None, 0, None, 0, None, 0, default))
    return rows


def efficiency(med, select):
    """per cell: performance of the selected candidate relative to the best"""
    return {p: med[p][select(p)] / max(med[p].values()) for p in med}


def write_table(setname, platform, data, tabledir, report):
    key = set_key(setname)
    s = cand.SETS[key]
    names = [c["name"] for c in s["candidates"] if not c.get("alias")]
    frames = {c["name"]: c["frame"] for c in s["candidates"]}
    info = {c["name"]: c for c in s["candidates"] if not c.get("alias")}
    med, passes, spread = load(data)
    ms = sorted({p[0] for p in med})
    ns = sorted({p[1] for p in med})
    ks = sorted({p[2] for p in med})
    bm, bn, bk = bounds(ms), bounds(ns), bounds(ks)
    default, win = winners(med, passes, names, info)
    ok = {p: [c for c in names if r.get(c, 0) >= (1 - NOISE) * max(r.values())]
          for p, r in med.items()}
    bx = boxes(win, ok, default, ms, ns, ks)

    ctype = s["type"]
    t = cand.TYPE_NAMES[ctype]
    fname = "%s-%s.h" % (platform, cpp_name(t))
    func = "gemm_%s_%s" % (cpp_name(platform), cpp_name(t))
    guard = "ULMBLAS_LEVEL3_GEMM_TABLES_%s_%s_H" % (cpp_name(platform).upper(),
                                                     cpp_name(t).upper())
    date = datetime.date.today().isoformat()
    old = os.path.join(tabledir, fname)
    if os.environ.get("GENTABLE_KEEP_DATE") and os.path.exists(old):
        m = re.search(r"generated by make tune on (\d{4}-\d{2}-\d{2})",
                      open(old).read())
        if m:
            date = m.group(1)

    def lim(v):
        return "GemmAll" if v is None else str(v)

    #  the table: the selection rules, or the boxes of merged cells with
    #  the best candidate (rules "boxes": a choice among many kernels)
    if s["rules"].get("boxes"):
        rows = box_rows(bx, default, bm, bn, bk)
        boxsel0 = {p: win[p] for p in med}
        select = lambda p: boxsel0[p]
        thresholds = {"boxes": len(bx), "default": default}
    else:
        rows, select, thresholds = fit_rules(med, s, ms, ns, ks, bm, bn, bk)

    #  for comparison in the report: the best candidate per cell (oracle),
    #  the boxes of cells (merged neighbouring cells), a single candidate
    boxsel = {p: win[p] for p in med}
    single = max(names, key=lambda c: sum(math.log(med[p][c] /
                                                   max(med[p].values()))
                                          for p in med))
    compare = [("best candidate per cell", efficiency(med, lambda p: max(
                    med[p], key=med[p].get))),
               ("selection rules (this table, %d entries)" % len(rows),
                efficiency(med, select)),
               ("boxes of merged cells (%d entries)" % (len(bx) + 1),
                efficiency(med, lambda p: boxsel[p])),
               ("one candidate for all (`%s`)" % single,
                efficiency(med, lambda p: single))]

    used = []
    for r in rows:
        if r[7] not in used:
            used.append(r[7])

    L = ["//",
         "//  Selection table of gemm for %s, packed blocks of type %s"
         % (platform, ctype),
         "//  (candidate set %s): generated by make tune on %s" % (setname, date),
         "//  (tune/gemm/gentable.py), do not edit.  See "
         "ulmblas/level3/gemm/select.h",
         "//  and the report tune/results/%s/%s.md." % (platform, setname),
         "//",
         "#ifndef %s" % guard,
         "#define %s 1" % guard,
         "",
         "#if %s" % s["condition"],
         "",
         "#include <cstddef>",
         "#include <ulmblas/level3/gemm/frame.h>",
         "#include <ulmblas/level3/gemm/plan.h>"]
    L += ["#include <%s>" % inc for inc in s["includes"]]
    L += ["",
          "#define ULMBLAS_GEMM_TABLE_%s_%s 1" % (cpp_name(platform).upper(),
                                                  cpp_name(t).upper()),
          "",
          "namespace ulmBLAS { namespace tables {",
          "",
          "//  the entries for operation Op (GemmOp, GemmtOp, ...; see "
          "ulmblas/level3/",
          "//  gemm/plan.h)",
          "template <typename Op>",
          "const Level3Entry<typename Op::Plan> *",
          "%s(std::size_t &count)" % func,
          "{",
          "    typedef %s B;" % s["backend"]]
    for c in used:
        L.append("    typedef %s" % frames[c].replace("GemmFrame<", "GemmFrame<"))
        L.append("        %s;" % cpp_name(c))
    L += ["",
          "    static const Level3Entry<typename Op::Plan> table[] = {",
          "        // clang-format off",
          "        // m              n              k              bytes of C "
          "(m n), of A (m k)"]
    for r in rows:
        c = r[7]
        mn = "0" if not r[6] else "std::size_t(%d) * Op::sizeC" % r[6]
        mk = "GemmBytesAll"
        if len(r) > 8 and r[8] is not None:
            mk = "std::size_t(%d) * Op::sizeA" % r[8]
        L.append("        {%s, %s,  %s, %s,  %s, %s,  %s,  %s," % (
            r[0], lim(r[1]), r[2], lim(r[3]), r[4], lim(r[5]), mn, mk))
        L.append('         Op::template plan<%s>("%s")},' % (cpp_name(c), c))
    L += ["        // clang-format on",
          "    };",
          "    count = sizeof(table) / sizeof(table[0]);",
          "    return table;",
          "}",
          "",
          "} } // namespace tables, ulmBLAS",
          "",
          "#endif // %s" % s["condition"],
          "",
          "#endif // %s" % guard]
    os.makedirs(tabledir, exist_ok=True)
    open(os.path.join(tabledir, fname), "w").write("\n".join(L) + "\n")
    write_index(tabledir)
    write_report(report, setname, platform, date, med, spread, names, rows,
                 thresholds, compare, ms, ns, ks)


