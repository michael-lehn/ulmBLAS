def write_index(tabledir):
    """tables.h: includes all tables, PlatformGemmTable<T>::entries"""
    tables = []
    for f in sorted(os.listdir(tabledir)):
        m = re.match(r"(.+)-(\w+)\.h$", f)
        if m and f != "tables.h":
            tables.append((f, m.group(1), m.group(2)))
    platforms = {"apple-m4": "AppleM4", "apple-m5": "AppleM5",
                 "intel-icelake": "IntelIceLake", "amd-zen4": "AmdZen4",
                 "intel-alderlake": "IntelAlderLake"}
    L = ["//",
         "//  Index of the generated selection tables of gemm: generated by",
         "//  make tune (tune/gemm/gentable.py), do not edit.",
         "//",
         "//  PlatformGemmTable<T>::entries<Op>(platform, count) returns the "
         "table for",
         "//  the platform and the type T of the packed blocks for operation Op "
         "(gemm,",
         "//  gemmt, ...; see ulmblas/level3/gemm/plan.h), nullptr if there is "
         "none",
         "//  (then the default table of the build is used, see",
         "//  ulmblas/level3/gemm/select.h).",
         "//",
         "#ifndef ULMBLAS_LEVEL3_GEMM_TABLES_TABLES_H",
         "#define ULMBLAS_LEVEL3_GEMM_TABLES_TABLES_H 1",
         "",
         "#include <complex>",
         "#include <cstddef>",
         "#include <ulmblas/config/platform.h>",
         "#include <ulmblas/level3/gemm/plan.h>"]
    L += ["#include <ulmblas/level3/gemm/tables/%s>" % f for f, _, _ in tables]
    L += ["",
          "namespace ulmBLAS {",
          "",
          "template <typename T> struct PlatformGemmTable",
          "{",
          "    template <typename Op>",
          "    static const Level3Entry<typename Op::Plan> *",
          "    entries(Platform platform, std::size_t &count)",
          "    {",
          "\treturn nullptr;",
          "    }",
          "};"]
    bytype = collections.defaultdict(list)
    for f, p, t in tables:
        bytype[t].append(p)
    for t, ps in sorted(bytype.items()):
        L += ["",
              "template <> struct PlatformGemmTable<%s>" % CTYPES.get(t, t),
              "{",
              "    template <typename Op>",
              "    static const Level3Entry<typename Op::Plan> *",
              "    entries(Platform platform, std::size_t &count)",
              "    {"]
        for p in ps:
            mac = "ULMBLAS_GEMM_TABLE_%s_%s" % (cpp_name(p).upper(),
                                                cpp_name(t).upper())
            L += ["#if defined(%s)" % mac,
                  "\tif (platform == Platform::%s) {" % platforms[p],
                  "\t    return tables::gemm_%s_%s<Op>(count);"
                  % (cpp_name(p), cpp_name(t)),
                  "\t}",
                  "#endif"]
        L += ["\treturn nullptr;", "    }", "};"]
    L += ["", "} // namespace ulmBLAS", "",
          "#endif // ULMBLAS_LEVEL3_GEMM_TABLES_TABLES_H"]
    open(os.path.join(tabledir, "tables.h"), "w").write("\n".join(L) + "\n")


def write_report(report, setname, platform, date, med, spread, names, rows,
                 thresholds, compare, ms, ns, ks):
    L = ["# GEMM tuning: %s, candidate set %s" % (platform, setname), "",
         "Generated by `make tune` on %s." % date, "",
         "Grid: m, n, k in %s (all combinations, %d shapes); median of the "
         "samples per shape and candidate over the passes." % (ms, len(med)),
         "",
         "## Selection rules", "",
         "Thresholds and global choices that maximize the geometric mean of "
         "the performance relative to the best candidate per cell "
         "(`None`: the rule does not apply):", "",
         "| Parameter | Value |", "|---|---|"]
    for k, v in thresholds.items():
        L.append("| `%s` | %s |" % (k, v))
    L += ["", "## Table", "",
          "| m | n | k | m n | m k | Candidate |", "|---|---|---|---|---|---|"]
    for r in rows:
        f = lambda a, b: "%d..%s" % (a, "∞" if b is None else b)
        mk = "<= %d" % r[8] if len(r) > 8 and r[8] is not None else ""
        L.append("| %s | %s | %s | >= %d | %s | `%s` |" % (
            f(r[0], r[1]), f(r[2], r[3]), f(r[4], r[5]), r[6], mk, r[7]))
    L += ["", "## Loss of merging", "",
          "Performance relative to the best candidate per cell, over the %d "
          "cells of the grid." % len(med), "",
          "| Selection | Geometric mean | Minimum | Cells below 0.97 |",
          "|---|---|---|---|"]
    for label, eff in compare:
        v = list(eff.values())
        gm = math.exp(sum(math.log(x) for x in v) / len(v))
        L.append("| %s | %.3f | %.3f | %d |" % (label, gm, min(v),
                                               sum(x < 0.97 for x in v)))
    eff = dict(compare)[[c[0] for c in compare][1]]
    worst = sorted(eff, key=eff.get)[:15]
    L += ["", "Cells with the largest loss of the selection rules:", "",
          "| m | n | k | Relative to the best | Best candidate |",
          "|---|---|---|---|---|"]
    for p in worst:
        L.append("| %d | %d | %d | %.3f | `%s` |" % (p + (eff[p], max(
            med[p], key=med[p].get))))
    L += ["", "## All measurements", "", "GFLOP/s (median).", "",
          "| m | n | k | " + " | ".join("`%s`" % c for c in names) + " |",
          "|---|---|---|" + "---|" * len(names)]
    for p in sorted(med):
        L.append("| %d | %d | %d | " % p + " | ".join(
            "%.1f" % med[p].get(c, 0) for c in names) + " |")
    os.makedirs(os.path.dirname(report), exist_ok=True)
    open(report, "w").write("\n".join(L) + "\n")


