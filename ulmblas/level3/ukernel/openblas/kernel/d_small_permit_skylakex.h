inline int CNAME(int transa, int transb, BLASLONG M, BLASLONG N, BLASLONG K, FLOAT alpha, FLOAT beta)
{
	double MNK = (double) M * (double) N * (double) K;
	if (MNK > 100.0*100.0*100.0)  // disable for big size matrix
		return 0;
	if (transa && !transb) {
		/* TN kernel perform not good when:
		 * 1. C matrix is too big
		 * 2. K is too small
		 */
		if (M * N > 1200 || K < 32)
			return 0;
	}
	return 1;
}

