//
//  The plan of operation Op (GemmOp, GemmtOp, ...; gemm/plan.h) for a
//  problem with dimensions m, n, k: the first entry of the table that
//  applies.  The table is the one generated for the platform (make tune,
//  ulmblas/level3/gemm/tables/), if there is one, otherwise the default
//  table of the build (GemmTable<T>).  Test configurations with their own
//  block sizes (USE_TESTPARAM) always use the default table.  Requires
//  k > 0 and alpha != 0 (handled by the wrappers).
//
template <typename T, typename Op>
typename Op::Plan
level3Select(std::ptrdiff_t m, std::ptrdiff_t n, std::ptrdiff_t k)
{
    typedef Level3Entry<typename Op::Plan> Entry;

    std::size_t count = 0;
    const Entry *table = nullptr;
#if !defined(USE_TESTPARAM)
    table = PlatformGemmTable<T>::template entries<Op>(platform(), count);
#endif
    if (!table) {
	table = GemmTable<T>::template entries<Op>(count);
    }
    for (std::size_t i = 0; i + 1 < count; ++i) {
	if (level3EntryApplies(table[i], m, n, k, Op::sizeC, Op::sizeA)) {
	    return table[i].plan;
	}
    }
    return table[count - 1].plan;
}

//
//  The plan of gemm for a problem.
//
template <typename IndexType, typename Alpha, typename TA, typename TB,
          typename Beta, typename TC>
GemmPlan<IndexType, Alpha, TA, TB, Beta, TC>
gemmSelect(const GemmProblem<IndexType> &problem)
{
    typedef decltype(Alpha(0) * TA(0) * TB(0)) T;

    return level3Select<T, GemmOp<IndexType, Alpha, TA, TB, Beta, TC>>(
        std::ptrdiff_t(problem.m), std::ptrdiff_t(problem.n),
        std::ptrdiff_t(problem.k));
}

