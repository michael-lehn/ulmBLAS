#!/usr/bin/env python3
"""
genshim.py MODE > shim.c

The ATL_ level 1 and 2 routines that the ATLAS testers (bench/l1blastst.c,
l2blastst.c) call as the "test" routines, implemented by ulmBLAS:

    MODE cblas   calls cblas_?xxx of ulmBLAS (libcblas.a)
    MODE f77     calls ?xxx_ of ulmBLAS (libf77blas.a); the trusted
                 reference BLAS is then built without trailing underscores

The testers pass vectors in ATLAS's convention: for inc < 0 the pointer is
the first element of the vector (the highest address).  The CBLAS and the
Fortran 77 interface expect the start of the array (the lowest address):
x + (n-1) inc.  For asum, amax, nrm2, scal and rscal ATLAS's trusted
wrappers (src/testing/ATL_f77*.c) call the reference with |inc| and the
start of the array; the shim does the same for them.
"""
import sys

MODE = sys.argv[1]
assert MODE in ("cblas", "f77")

R = {"s": "float", "d": "double", "c": "float", "z": "double"}
CPLX = {"s": False, "d": False, "c": True, "z": True}
RP = {"c": "s", "z": "d"}  # real prefix of a complex type
UP = {"s": "S", "d": "D", "c": "C", "z": "Z"}

out = []
w = out.append

w("/* generated by genshim.py %s: ATL_ level 1 and 2 -> ulmBLAS (test only) */" % MODE)
w("#include <complex.h>")
w("#include <stddef.h>")
w("#include <stdio.h>")
w("#include <stdlib.h>")
w("")
w("enum { NoTrans = 111, Trans = 112, ConjTrans = 113 };")
w("enum { Upper = 121, Lower = 122 };")
w("enum { NonUnit = 131, Unit = 132 };")
w("enum { ColMajor = 102 };")
w("")
w("/* the start of the array of a vector given in ATLAS's convention */")
w("#define START(x, n, inc, cplx) \\")
w("    ((inc) < 0 && (n) > 0 ? (x) + (ptrdiff_t)((n) - 1) * (inc) * ((cplx) ? 2 : 1) : (x))")
w("#define ABS(i) ((i) < 0 ? -(i) : (i))")
w("")

if MODE == "f77":
    w("static const char *trans(int t) { return t == NoTrans ? \"N\" : t == Trans ? \"T\" : \"C\"; }")
    w("static const char *uplo(int u) { return u == Upper ? \"U\" : \"L\"; }")
    w("static const char *diag(int d) { return d == Unit ? \"U\" : \"N\"; }")
    w("")

w("void ATL_xerbla(int p, const char *rout, const char *form, ...)")
w("{")
w("    fprintf(stderr, \"ATL_xerbla: parameter %d of %s\\n\", p, rout);")
w("}")
w("")


def decl_f77(name, ret, params):
    w("%s %s_(%s);" % (ret, name, ", ".join(params)))


# ---------------------------------------------------------------- level 1
for p in "sdcz":
    T = R[p]
    c = CPLX[p]
    cs = "1" if c else "0"
    rp = RP.get(p, p)
    # asum, nrm2 (|inc|, start)
    for f, name in (("asum", (rp + "asum") if not c else (rp + p + "asum")),
                    ("nrm2", (rp + "nrm2") if not c else (rp + p + "nrm2"))):
        atl = "ATL_%s" % name
        if MODE == "cblas":
            call = "cblas_%s(N, START(X, N, incX, %s), ABS(incX))" % (name, cs)
        else:
            decl_f77(name, T, ["const int *n", "const %s *x" % T, "const int *incX"])
            call = "%s_(&N, START(X, N, incX, %s), &ai)" % (name, cs)
        w("%s %s(const int N, const %s *X, const int incX)" % (T, atl, T))
        w("{")
        w("    const int ai = ABS(incX);")
        w("    (void)ai;")
        w("    return %s;" % call)
        w("}")
    # amax: 0-based index, |inc|, start
    name = "i%samax" % p
    if MODE == "cblas":
        call = "(int)cblas_%s(N, START(X, N, incX, %s), ABS(incX))" % (name, cs)
    else:
        decl_f77(name, "int", ["const int *n", "const %s *x" % T, "const int *incX"])
        call = "%s_(&N, START(X, N, incX, %s), &ai) - 1" % (name, cs)
    w("int ATL_%s(const int N, const %s *X, const int incX)" % (name, T))
    w("{")
    w("    const int ai = ABS(incX);")
    w("    (void)ai;")
    w("    if (N <= 0) return 0;")
    w("    return %s;" % call)
    w("}")
    # scal (|inc|, start), alpha scalar or pointer
    a_t = ("const %s *alpha" % T) if c else ("const %s alpha" % T)
    if MODE == "cblas":
        call = "cblas_%sscal(N, alpha, START(X, N, incX, %s), ABS(incX))" % (p, cs)
    else:
        decl_f77(p + "scal", "void", ["const int *n", "const %s *alpha" % T, "%s *x" % T, "const int *incX"])
        call = "%sscal_(&N, %s, START(X, N, incX, %s), &ai)" % (p, "alpha" if c else "&alpha", cs)
    w("void ATL_%sscal(const int N, %s, %s *X, const int incX)" % (p, a_t, T))
    w("{")
    w("    const int ai = ABS(incX);")
    w("    (void)ai;")
    w("    %s;" % call)
    w("}")
    if c:
        # rscal: csscal / zdscal
        name = p + rp + "scal"
        if MODE == "cblas":
            call = "cblas_%s(N, alpha, START(X, N, incX, 1), ABS(incX))" % name
        else:
            decl_f77(name, "void", ["const int *n", "const %s *alpha" % T, "%s *x" % T, "const int *incX"])
            call = "%s_(&N, &alpha, START(X, N, incX, 1), &ai)" % name
        w("void ATL_%s(const int N, const %s alpha, %s *X, const int incX)" % (name, T, T))
        w("{")
        w("    const int ai = ABS(incX);")
        w("    (void)ai;")
        w("    %s;" % call)
        w("}")
    # axpy, copy, swap
    for f, params, cargs, fargs in (
        ("axpy", "const int N, %s, const %s *X, const int incX, %s *Y, const int incY" % (a_t, T, T),
         "N, alpha, %s, incX, %s, incY",
         "&N, %s, %%s, &incX, %%s, &incY" % ("alpha" if c else "&alpha")),
        ("copy", "const int N, const %s *X, const int incX, %s *Y, const int incY" % (T, T),
         "N, %s, incX, %s, incY", "&N, %s, &incX, %s, &incY"),
        ("swap", "const int N, %s *X, const int incX, %s *Y, const int incY" % (T, T),
         "N, %s, incX, %s, incY", "&N, %s, &incX, %s, &incY")):
        xs = "START(X, N, incX, %s)" % cs
        ys = "START(Y, N, incY, %s)" % cs
        if MODE == "cblas":
            call = "cblas_%s%s(%s)" % (p, f, cargs % (xs, ys))
        else:
            fp = ["const int *n"]
            if f == "axpy":
                fp.append("const %s *alpha" % T)
            fp += ["%s%s *x" % ("const " if f != "swap" else "", T), "const int *incX", "%s *y" % T, "const int *incY"]
            decl_f77(p + f, "void", fp)
            call = "%s%s_(%s)" % (p, f, fargs % (xs, ys))
        w("void ATL_%s%s(%s)" % (p, f, params))
        w("{")
        w("    %s;" % call)
        w("}")
    xs = "START(X, N, incX, %s)" % cs
    ys = "START(Y, N, incY, %s)" % cs
    if not c:
        # dot
        if MODE == "cblas":
            call = "cblas_%sdot(N, %s, incX, %s, incY)" % (p, xs, ys)
        else:
            decl_f77(p + "dot", T, ["const int *n", "const %s *x" % T, "const int *incX", "const %s *y" % T, "const int *incY"])
            call = "%sdot_(&N, %s, &incX, %s, &incY)" % (p, xs, ys)
        w("%s ATL_%sdot(const int N, const %s *X, const int incX, const %s *Y, const int incY)" % (T, p, T, T))
        w("{")
        w("    return %s;" % call)
        w("}")
        # rot, rotm, rotg, rotmg
        if MODE == "cblas":
            call = "cblas_%srot(N, %s, incX, %s, incY, c, s)" % (p, xs, ys)
        else:
            decl_f77(p + "rot", "void", ["const int *n", "%s *x" % T, "const int *incX", "%s *y" % T, "const int *incY", "const %s *c" % T, "const %s *s" % T])
            call = "%srot_(&N, %s, &incX, %s, &incY, &c, &s)" % (p, xs, ys)
        w("void ATL_%srot(const int N, %s *X, const int incX, %s *Y, const int incY, const %s c, const %s s)" % (p, T, T, T, T))
        w("{")
        w("    %s;" % call)
        w("}")
        if MODE == "cblas":
            call = "cblas_%srotm(N, %s, incX, %s, incY, P)" % (p, xs, ys)
        else:
            decl_f77(p + "rotm", "void", ["const int *n", "%s *x" % T, "const int *incX", "%s *y" % T, "const int *incY", "const %s *P" % T])
            call = "%srotm_(&N, %s, &incX, %s, &incY, P)" % (p, xs, ys)
        w("void ATL_%srotm(const int N, %s *X, const int incX, %s *Y, const int incY, const %s *P)" % (p, T, T, T))
        w("{")
        w("    %s;" % call)
        w("}")
        if MODE == "cblas":
            call = "cblas_%srotg(a, b, c, s)" % p
        else:
            decl_f77(p + "rotg", "void", ["%s *a" % T, "%s *b" % T, "%s *c" % T, "%s *s" % T])
            call = "%srotg_(a, b, c, s)" % p
        w("void ATL_%srotg(%s *a, %s *b, %s *c, %s *s)" % (p, T, T, T, T))
        w("{")
        w("    %s;" % call)
        w("}")
        if MODE == "cblas":
            call = "cblas_%srotmg(d1, d2, b1, b2, P)" % p
        else:
            decl_f77(p + "rotmg", "void", ["%s *d1" % T, "%s *d2" % T, "%s *b1" % T, "const %s *b2" % T, "%s *P" % T])
            call = "%srotmg_(d1, d2, b1, &b2, P)" % p
        w("void ATL_%srotmg(%s *d1, %s *d2, %s *b1, const %s b2, %s *P)" % (p, T, T, T, T, T))
        w("{")
        w("    %s;" % call)
        w("}")
        if p == "s":
            if MODE == "cblas":
                call = "cblas_sdsdot(N, b, %s, incX, %s, incY)" % (xs, ys)
            else:
                decl_f77("sdsdot", "float", ["const int *n", "const float *b", "const float *x", "const int *incX", "const float *y", "const int *incY"])
                call = "sdsdot_(&N, &b, %s, &incX, %s, &incY)" % (xs, ys)
            w("float ATL_sdsdot(const int N, const float b, const float *X, const int incX, const float *Y, const int incY)")
            w("{")
            w("    return %s;" % call)
            w("}")
        else:
            xs2 = "START(X, N, incX, 0)"
            ys2 = "START(Y, N, incY, 0)"
            if MODE == "cblas":
                call = "cblas_dsdot(N, %s, incX, %s, incY)" % (xs2, ys2)
            else:
                decl_f77("dsdot", "double", ["const int *n", "const float *x", "const int *incX", "const float *y", "const int *incY"])
                call = "dsdot_(&N, %s, &incX, %s, &incY)" % (xs2, ys2)
            w("double ATL_dsdot(const int N, const float *X, const int incX, const float *Y, const int incY)")
            w("{")
            w("    return %s;" % call)
            w("}")
    else:
        # dotc_sub, dotu_sub
        for f in ("dotc", "dotu"):
            if MODE == "cblas":
                call = "cblas_%s%s_sub(N, %s, incX, %s, incY, dot)" % (p, f, xs, ys)
                body = "    %s;" % call
            else:
                ct = "float _Complex" if p == "c" else "double _Complex"
                decl_f77(p + f, ct, ["const int *n", "const %s *x" % T, "const int *incX", "const %s *y" % T, "const int *incY"])
                body = ("    %s r = %s%s_(&N, %s, &incX, %s, &incY);\n"
                        "    dot[0] = creal(r);\n    dot[1] = cimag(r);") % (ct, p, f, xs, ys)
            w("void ATL_%s%s_sub(const int N, const %s *X, const int incX, const %s *Y, const int incY, %s *dot)" % (p, f, T, T, T))
            w("{")
            w(body)
            w("}")
        # csrot / zdrot
        name = p + rp + "rot"
        if MODE == "cblas":
            call = "cblas_%s(N, %s, incX, %s, incY, c, s)" % (name, xs, ys)
        else:
            decl_f77(name, "void", ["const int *n", "%s *x" % T, "const int *incX", "%s *y" % T, "const int *incY", "const %s *c" % T, "const %s *s" % T])
            call = "%s_(&N, %s, &incX, %s, &incY, &c, &s)" % (name, xs, ys)
        w("void ATL_%s(const int N, %s *X, const int incX, %s *Y, const int incY, const %s c, const %s s)" % (name, T, T, T, T))
        w("{")
        w("    %s;" % call)
        w("}")
        # crotg / zrotg
        if MODE == "cblas":
            call = "cblas_%srotg(a, (void *)b, c, s)" % p
        else:
            decl_f77(p + "rotg", "void", ["%s *a" % T, "const %s *b" % T, "%s *c" % T, "%s *s" % T])
            call = "%srotg_(a, b, c, s)" % p
        w("void ATL_%srotg(%s *a, const %s *b, %s *c, %s *s)" % (p, T, T, T, T))
        w("{")
        w("    %s;" % call)
        w("}")
    w("")

# ---------------------------------------------------------------- level 2
for p in "sdcz":
    T = R[p]
    c = CPLX[p]
    cs = "1" if c else "0"
    al = ("const %s *alpha" % T) if c else ("const %s alpha" % T)
    be = ("const %s *beta" % T) if c else ("const %s beta" % T)
    aref = "alpha" if c else "&alpha"
    bref = "beta" if c else "&beta"

    def emit(name, params, cblas_call, f77_decl, f77_call, pre=""):
        if MODE == "f77":
            decl_f77(*f77_decl)
        w("void ATL_%s%s(%s)" % (p, name, params))
        w("{")
        if pre:
            w(pre)
        w("    %s;" % (cblas_call if MODE == "cblas" else f77_call))
        w("}")

    lenxy = ("    const int lx = TA == NoTrans ? N : M, ly = TA == NoTrans ? M : N;\n"
             "    const %s *x = START(X, lx, incX, %s);\n"
             "    %s *y = START(Y, ly, incY, %s);") % (T, cs, T, cs)
    # gemv
    emit("gemv", "const int TA, const int M, const int N, %s, const %s *A, const int lda, const %s *X, const int incX, %s, %s *Y, const int incY" % (al, T, T, be, T),
         "cblas_%sgemv(ColMajor, TA, M, N, alpha, A, lda, x, incX, beta, y, incY)" % p,
         (p + "gemv", "void", ["const char *t", "const int *m", "const int *n", "const %s *alpha" % T, "const %s *A" % T, "const int *lda", "const %s *x" % T, "const int *incX", "const %s *beta" % T, "%s *y" % T, "const int *incY", "size_t lt"]),
         "%sgemv_(trans(TA), &M, &N, %s, A, &lda, x, &incX, %s, y, &incY, 1)" % (p, aref, bref), lenxy)
    emit("gbmv", "const int TA, const int M, const int N, const int KL, const int KU, %s, const %s *A, const int lda, const %s *X, const int incX, %s, %s *Y, const int incY" % (al, T, T, be, T),
         "cblas_%sgbmv(ColMajor, TA, M, N, KL, KU, alpha, A, lda, x, incX, beta, y, incY)" % p,
         (p + "gbmv", "void", ["const char *t", "const int *m", "const int *n", "const int *kl", "const int *ku", "const %s *alpha" % T, "const %s *A" % T, "const int *lda", "const %s *x" % T, "const int *incX", "const %s *beta" % T, "%s *y" % T, "const int *incY", "size_t lt"]),
         "%sgbmv_(trans(TA), &M, &N, &KL, &KU, %s, A, &lda, x, &incX, %s, y, &incY, 1)" % (p, aref, bref), lenxy)
    lenn = ("    const %s *x = START(X, N, incX, %s);\n"
            "    %s *y = START(Y, N, incY, %s);") % (T, cs, T, cs)
    sy = "he" if c else "sy"
    sp = "hp" if c else "sp"
    sb = "hb" if c else "sb"
    emit(sy + "mv", "const int U, const int N, %s, const %s *A, const int lda, const %s *X, const int incX, %s, %s *Y, const int incY" % (al, T, T, be, T),
         "cblas_%s%smv(ColMajor, U, N, alpha, A, lda, x, incX, beta, y, incY)" % (p, sy),
         (p + sy + "mv", "void", ["const char *u", "const int *n", "const %s *alpha" % T, "const %s *A" % T, "const int *lda", "const %s *x" % T, "const int *incX", "const %s *beta" % T, "%s *y" % T, "const int *incY", "size_t lu"]),
         "%s%smv_(uplo(U), &N, %s, A, &lda, x, &incX, %s, y, &incY, 1)" % (p, sy, aref, bref), lenn)
    emit(sb + "mv", "const int U, const int N, const int K, %s, const %s *A, const int lda, const %s *X, const int incX, %s, %s *Y, const int incY" % (al, T, T, be, T),
         "cblas_%s%smv(ColMajor, U, N, K, alpha, A, lda, x, incX, beta, y, incY)" % (p, sb),
         (p + sb + "mv", "void", ["const char *u", "const int *n", "const int *k", "const %s *alpha" % T, "const %s *A" % T, "const int *lda", "const %s *x" % T, "const int *incX", "const %s *beta" % T, "%s *y" % T, "const int *incY", "size_t lu"]),
         "%s%smv_(uplo(U), &N, &K, %s, A, &lda, x, &incX, %s, y, &incY, 1)" % (p, sb, aref, bref), lenn)
    emit(sp + "mv", "const int U, const int N, %s, const %s *Ap, const %s *X, const int incX, %s, %s *Y, const int incY" % (al, T, T, be, T),
         "cblas_%s%smv(ColMajor, U, N, alpha, Ap, x, incX, beta, y, incY)" % (p, sp),
         (p + sp + "mv", "void", ["const char *u", "const int *n", "const %s *alpha" % T, "const %s *Ap" % T, "const %s *x" % T, "const int *incX", "const %s *beta" % T, "%s *y" % T, "const int *incY", "size_t lu"]),
         "%s%smv_(uplo(U), &N, %s, Ap, x, &incX, %s, y, &incY, 1)" % (p, sp, aref, bref), lenn)
    lenx = "    %s *x = START(X, N, incX, %s);" % (T, cs)
    for f in ("mv", "sv"):
        emit("tr" + f, "const int U, const int TA, const int D, const int N, const %s *A, const int lda, %s *X, const int incX" % (T, T),
             "cblas_%str%s(ColMajor, U, TA, D, N, A, lda, x, incX)" % (p, f),
             (p + "tr" + f, "void", ["const char *u", "const char *t", "const char *d", "const int *n", "const %s *A" % T, "const int *lda", "%s *x" % T, "const int *incX", "size_t lu", "size_t lt", "size_t ld"]),
             "%str%s_(uplo(U), trans(TA), diag(D), &N, A, &lda, x, &incX, 1, 1, 1)" % (p, f), lenx)
        emit("tb" + f, "const int U, const int TA, const int D, const int N, const int K, const %s *A, const int lda, %s *X, const int incX" % (T, T),
             "cblas_%stb%s(ColMajor, U, TA, D, N, K, A, lda, x, incX)" % (p, f),
             (p + "tb" + f, "void", ["const char *u", "const char *t", "const char *d", "const int *n", "const int *k", "const %s *A" % T, "const int *lda", "%s *x" % T, "const int *incX", "size_t lu", "size_t lt", "size_t ld"]),
             "%stb%s_(uplo(U), trans(TA), diag(D), &N, &K, A, &lda, x, &incX, 1, 1, 1)" % (p, f), lenx)
        emit("tp" + f, "const int U, const int TA, const int D, const int N, const %s *Ap, %s *X, const int incX" % (T, T),
             "cblas_%stp%s(ColMajor, U, TA, D, N, Ap, x, incX)" % (p, f),
             (p + "tp" + f, "void", ["const char *u", "const char *t", "const char *d", "const int *n", "const %s *Ap" % T, "%s *x" % T, "const int *incX", "size_t lu", "size_t lt", "size_t ld"]),
             "%stp%s_(uplo(U), trans(TA), diag(D), &N, Ap, x, &incX, 1, 1, 1)" % (p, f), lenx)
    lenmn = ("    const %s *x = START(X, M, incX, %s);\n"
             "    const %s *y = START(Y, N, incY, %s);") % (T, cs, T, cs)
    for g in (("geru", "gerc") if c else ("ger",)):
        emit(g, "const int M, const int N, %s, const %s *X, const int incX, const %s *Y, const int incY, %s *A, const int lda" % (al, T, T, T),
             "cblas_%s%s(ColMajor, M, N, alpha, x, incX, y, incY, A, lda)" % (p, g),
             (p + g, "void", ["const int *m", "const int *n", "const %s *alpha" % T, "const %s *x" % T, "const int *incX", "const %s *y" % T, "const int *incY", "%s *A" % T, "const int *lda"]),
             "%s%s_(&M, &N, %s, x, &incX, y, &incY, A, &lda)" % (p, g, aref), lenmn)
    # syr / her, spr / hpr: alpha real
    r1 = "her" if c else "syr"
    p1 = "hpr" if c else "spr"
    lenx1 = "    const %s *x = START(X, N, incX, %s);" % (T, cs)
